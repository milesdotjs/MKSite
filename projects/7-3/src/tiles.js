/* ============================================================
   7-3 — 8x8 tile set

   Digits are palette indices (0 lightest .. 3 darkest), so every
   tile re-colours for free when an area swaps its palette. A
   tile is `solid` if it blocks movement and `task` if standing
   on it can spin up a random encounter — this game's tall grass.
   ============================================================ */

import { sprite } from './gfx.js';

const T = (name, art, opts = {}) => ({
  name,
  art: sprite(art),
  solid: !!opts.solid,
  task: !!opts.task,
  rate: opts.rate || 0,
  tall: !!opts.tall, // drawn over the player's feet for depth
});

/* prettier-ignore */
export const TILE = {};
let nextId = 0;
const def = (name, art, opts) => {
  const t = T(name, art, opts);
  t.id = nextId++;
  TILE[name] = t;
  return t;
};

