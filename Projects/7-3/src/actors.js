/**
 * An actor sprite set. NPCs reuse the salaryman's back and side
 * views — they are only ever seen head-on long enough to matter.
 */
function set(down, up, side) {
  return { down, up, side };
}

export const ACTORS = {
  salaryman: set(
    [SALARY_DOWN_0, SALARY_DOWN_1],
    [SALARY_UP_0, SALARY_UP_1],
    [SALARY_SIDE_0, SALARY_SIDE_1]
  ),
  bob: set([BOB_DOWN_0, BOB_DOWN_1], [SALARY_UP_0, SALARY_UP_1], [SALARY_SIDE_0, SALARY_SIDE_1]),
  senior: set(
    [SENIOR_DOWN_0, SENIOR_DOWN_1],
    [SALARY_UP_0, SALARY_UP_1],
    [SALARY_SIDE_0, SALARY_SIDE_1]
  ),
  clerk: set(
    [CLERK_DOWN_0, CLERK_DOWN_1],
    [SALARY_UP_0, SALARY_UP_1],
    [SALARY_SIDE_0, SALARY_SIDE_1]
  ),
};

export const ACTOR_KINDS = Object.keys(ACTORS);

/** Pick the frame for a facing + walk phase. Returns [sprite, flipX]. */
export function actorFrame(kind, facing, phase) {
  const a = ACTORS[kind] || ACTORS.salaryman;
  const f = phase & 1;
  if (facing === 'up') return [a.up[f], false];
  if (facing === 'down') return [a.down[f], false];
  return [a.side[f], facing === 'left'];
}

