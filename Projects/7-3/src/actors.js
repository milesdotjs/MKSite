/* ============================================================
   Battle back-sprite — the player, seen from behind, holding the
   bag. Built from primitives because it is bigger than the ASCII
   grid comfortably handles.
   ============================================================ */

function backSprite() {
  const c = canvas(52, 48);
  // shoulders: a trapezoid that widens toward the bottom of the frame
  for (let y = 0; y < 20; y++) {
    const w = Math.round(24 + y * 1.05);
    rect(c, Math.round(26 - w / 2), 28 + y, w, 1, 1);
  }
  // a hint of a collar, and the back of a tie knot
  rect(c, 20, 28, 12, 3, 0);
  line(c, 21, 30, 26, 35, 3);
  line(c, 31, 30, 26, 35, 3);
  // shading down the left side, so the torso has a light source
  shade(c, 8, 36, 12, 12, 2);
  // head, from behind: all hair, with a little shine on the crown
  disc(c, 26, 16, 13, 3);
  ellipse(c, 26, 10, 7, 3, 2);
  // one clean silhouette
  outline(c, 3);
  // the bag, held low and slightly behind
  box(c, 0, 33, 12, 12, 2, 3);
  rect(c, 2, 31, 8, 2, 3);
  rect(c, 0, 37, 12, 1, 3);
  return c;
}

export const PLAYER_BACK = backSprite();
