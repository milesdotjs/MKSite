for (const [ch, art] of PUNCT) G[ch] = art;

/** char -> { w, bits: Uint8Array(8) }, bit 7 = leftmost pixel */
const GLYPHS = new Map();
for (const [ch, art] of Object.entries(G)) {
  const rows = art.split('/');
  const w = Math.max(...rows.map((r) => r.length));
  const bits = new Uint8Array(8);
  for (let y = 0; y < 8; y++) {
    const row = rows[y] || '';
    let m = 0;
    for (let x = 0; x < w; x++) if (row[x] === '#') m |= 0x80 >> x;
    bits[y] = m;
  }
  GLYPHS.set(ch, { w, bits });
}

const FALLBACK = GLYPHS.get('?');

export const LINE_H = 10; // 8px cell + 2px leading
export const TRACKING = 1;
const SPACE_W = 3;

export function glyph(ch) {
  return GLYPHS.get(ch) || FALLBACK;
}

/** Advance width of one character, in pixels. */
export function charW(ch) {
  return (ch === ' ' ? SPACE_W : glyph(ch).w) + TRACKING;
}

/** Pixel width of a string, ignoring wrapping. */
export function textW(str) {
  let w = 0;
  for (const ch of str) w += charW(ch);
  return w > 0 ? w - TRACKING : 0;
}

/** Greedy word wrap to a pixel width. Honours explicit newlines. */
export function wrap(str, maxW) {
  const out = [];
  for (const para of String(str).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const probe = line ? line + ' ' + word : word;
      if (textW(probe) <= maxW || !line) line = probe;
      else {
        out.push(line);
        line = word;
      }
    }
    out.push(line);
  }
  return out;
}

